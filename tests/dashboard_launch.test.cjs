'use strict';
const fs = require('fs');
const assert = require('assert').strict;
const source = fs.readFileSync('src/Program.cs', 'utf8');
const start = source.indexOf('public static void LaunchDashboard(string appDir)');
const end = source.indexOf('private void CheckSchedulerTick()', start);
assert(start >= 0 && end > start, 'Dashboard launcher must exist');
const launch = source.slice(start, end);
assert.match(launch, /dashboardUrl = "http:\/\/127\.0\.0\.1:6801\//, 'Dashboard URL must target the local app');
assert.match(launch, /FileName = dashboardUrl/, 'Use Windows URL association');
assert.match(launch, /UseShellExecute = true/, 'Windows must choose the configured default browser');
assert.doesNotMatch(launch, /FindChromiumBrowser|msedge\.exe|chrome\.exe|brave\.exe|--app=|--user-data-dir=/, 'Do not spawn a dedicated browser or profile');
assert.match(source, /public void LaunchDefaultBrowser\(\)/, 'Tray and startup use the default browser launcher');
assert.doesNotMatch(source, /LaunchEdgeApp|FindChromiumBrowser|IsExpectedBrowserPath/, 'Remove hard-coded browser selection');
assert.doesNotMatch(source, /if \(!WindowManager\.FocusExistingWindow\(\)\)\s*\{\s*DownloaderAppContext\.LaunchDashboard/, 'Reopening dashboard must not depend on Chromium window detection');
console.log('PASS: dashboard uses the Windows default browser for all app entry points');
