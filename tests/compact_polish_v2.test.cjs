'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('ui/index.html','utf8');
const css=fs.readFileSync('ui/compact-desktop.css','utf8');

const head=html.slice(html.indexOf('<div class="engine-status-group"'),html.indexOf('<div class="action-toolbar"'));
const ids=['themeToggleBtn','langToggleBtn','systemStatusPill','headerLayoutBtn','headerMoreBtn'];
assert.equal((head.match(/<button\b/g)||[]).length,5,'exactly five top-right buttons');
for(const id of ids) assert.ok(head.includes('id="'+id+'"'),id+' is present');
assert.match(css,/\.compact-brand-name \{display:none !important;\}/,'native titlebar is the only visible app name');
assert.match(html,/id="headerMoreMenu" class="context-menu"/,'secondary controls have an overflow menu');
assert.match(html,/id="notificationToggleBtn"/,'notification toggle preserved');
assert.match(html,/id="notificationToggleText"/,'live notification status preserved');
assert.match(html,/id="supportBtn"/,'support control preserved');
assert.match(html,/id="systemStatusDot"/,'live update status indicator preserved');
assert.match(html,/id="headerLayoutBtn" onclick="openColumnCustomizer\(event\)"/);
assert.match(html,/onclick="openToolbarCustomizer\(event\)"/,'toolbar configuration remains available');
const toolbar=html.slice(html.indexOf('<div class="action-toolbar"'),html.indexOf('<!-- BODY (SIDEBAR',html.indexOf('<div class="action-toolbar"')));
assert.doesNotMatch(toolbar,/btn-tb-customize/,'remove duplicate, rotating customization icons');
assert.match(html,/const more = document\.getElementById\('headerMoreMenu'\)/,'more menu closes with all context menus');
assert.match(html,/function toggleHeaderMoreMenu\(e\)/);
assert.match(html,/applyTheme\(currentTheme === 'light' \? 'dark' : 'light'\)/,'primary theme cycles only between light and dark');
assert.match(html,/langBtn\.textContent = lang === 'ar' \? 'EN' : 'AR'/,'compact language switching');
assert.match(css,/#toolbarContextMenu,#headerContextMenu/,'compact settings popovers');
assert.match(css,/\.context-menu, \.system-status-popover, #headerMoreMenu \{/,'all popovers follow theme');
assert.match(css,/background:var\(--bg-surface\) !important;/,'use variable-based popover background');
assert.match(css,/\.btn-add-primary:hover \{background:#078b68 !important;box-shadow:none !important;\}/,'non-animated primary hover');
assert.match(css,/\.btn:hover,\.btn:active,\.btn-add-primary:hover,\.btn-tb-customize:hover,[\s\S]*?transform:none !important;/,'disable playful transforms for all hover actions');
assert.match(html,/function updateCompactHeading\(visibleCount\)/,'preserve live row count');
assert.match(html,/function updateNotificationButton\(\)/,'preserve notification status logic');
console.log('PASS: compact v2 header, stable hover, overflow actions and theme-aware popovers');